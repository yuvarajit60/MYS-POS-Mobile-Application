/*
  Income or Expenses — mobile entry for the desktop app's existing
  dbo.HEAD / dbo.INCOMEOREXPENSES feature (confirmed via read-only check:
  both already exist on db_ams_erp/DB_AMS_ERP_SMS with live data, e.g.
  ENTRYNO "IE/26-27/2104", and a live TRANSACTIONS row NAME=
  'INCOMEOREXPENSES' SHORTNAME='IE/26-27/' — same shared-sequence
  convention as every other entry type here). This script only creates
  the two tables where missing (the sandbox, seeded with the same 13 HEAD
  rows shown in the desktop reference screenshot, IDs preserved via
  IDENTITY_INSERT) and adds two new mobile-only columns.

  EMPLOYEEID/VEHICLEID (both nullable) are new — PARTICULARS is desktop's
  only free-text field (e.g. "KUMAR ADVANCE", typed by hand), but the
  mobile app picks a structured Employee for the "SALARY ADVANCE" head and
  a structured Vehicle for the "FUEL" head instead, storing the id here
  while still writing a sensible PARTICULARS string for desktop-side
  compatibility (see IncomeExpenseService.CreateAsync).

  Idempotent — safe to re-run.
*/

