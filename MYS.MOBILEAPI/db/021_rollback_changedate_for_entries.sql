/*
  Rollback: SALESORDER.ENTRYDATE, TRIPENTRY.ENTRYDATE, and
  DELIVERY_DETAILS.DELIVERDATE go back to GETDATE() instead of
  dbo.CHANGE_DATE (016_current_date_entrydate.sql). The desktop app's
  "business date" in CHANGE_DATE could sit days behind the real date
  until someone ran a "day close" there, which caused more confusion
  than it solved for these three tables — requested rollback.

  dbo.CHANGE_DATE itself is NOT dropped and NOT touched by this script —
  Payment Entry's PAYMENTDATE (see 017_payment_details.sql,
  SP_MOBILE_CREATE_PAYMENT) still reads it and is unaffected; only
  SALESORDER/TRIPENTRY/DELIVERY's own date stamps change back.

  TRIPENTRY.TRIPDATE was never tied to CHANGE_DATE — it has always been
  (and remains) exactly whatever date the rep entered on the Trip Date
  picker, passed straight through as @TRIPDATE. No change needed there;
  called out here only because the request that prompted this rollback
  named it explicitly.

  Table-valued parameter TYPEs (TVP_MOBILE_SALESORDER_LINES/
  TVP_MOBILE_TRIPENTRY_LINES/TVP_MOBILE_DELIVERY_LINES) are unchanged in
  shape by this rollback, so only the three procedures are dropped and
  recreated here — no type changes needed.

  Idempotent — safe to re-run.
*/

