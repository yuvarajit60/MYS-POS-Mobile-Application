IF OBJECT_ID(N'dbo.INCOMEOREXPENSES', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.INCOMEOREXPENSES
    (
        INCOMEOREXPENSESID INT IDENTITY(1,1) NOT NULL,
        ENTRYNO             VARCHAR(30) NULL,
        ENTRYDATE           DATETIME NULL,
        ENTRYTIME           DATETIME NULL,
        LOCATIONID          INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_LOCATIONID DEFAULT 0,
        COMPANYID           INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_COMPANYID DEFAULT 0,
        INCOMEOREXPENSES    VARCHAR(30) NULL,
        HEADID              INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_HEADID DEFAULT 0,
        PARTICULARS         VARCHAR(50) NULL,
        AMOUNT              NUMERIC(18,0) NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_AMOUNT DEFAULT 0,
        CANCEL              BIT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_CANCEL DEFAULT 0,
        CANCELDATE          DATETIME NULL,
        CANCELUSERID        INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_CANCELUSERID DEFAULT 0,
        CREATEDLOCATIONID   INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_CREATEDLOCATIONID DEFAULT 0,
        MODIFYEDLOCATIONID  INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_MODIFYEDLOCATIONID DEFAULT 0,
        CREATEDUSERID       INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_CREATEDUSERID DEFAULT 0,
        LASTMODIFYEDUSERID  INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_LASTMODIFYEDUSERID DEFAULT 0,
        USERCREATEDDATE     DATETIME NULL,
        LASTMODIFYEDDATE    DATETIME NULL,
        CREATEDEMPLOYEEID   INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_CREATEDEMPLOYEEID DEFAULT 0,
        MODIFYEDEMPLOYEEID  INT NOT NULL CONSTRAINT DF_INCOMEOREXPENSES_MODIFYEDEMPLOYEEID DEFAULT 0,
        EMPLOYEEID          INT NULL,
        VEHICLEID           INT NULL
    );
END
GO

IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'INCOMEOREXPENSES' AND COLUMN_NAME = 'EMPLOYEEID')
    ALTER TABLE dbo.INCOMEOREXPENSES ADD EMPLOYEEID INT NULL;
GO
IF NOT EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'INCOMEOREXPENSES' AND COLUMN_NAME = 'VEHICLEID')
    ALTER TABLE dbo.INCOMEOREXPENSES ADD VEHICLEID INT NULL;
GO
